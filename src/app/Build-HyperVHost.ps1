param(
    [Parameter(Mandatory = $true)][ValidateSet('Read', 'ReadExisting', 'Run')][string]$Mode,
    [Parameter(Mandatory = $true)][string]$ResultPath,
    [string]$Computers = '',
    [string]$StepPath = '',
    [string]$ApprovedPath = '',
    [switch]$Apply,
    [switch]$RestartAfter,
    [switch]$CredentialFromInput
)

# Builds Hyper-V hosts and failover clusters for Build Hyper-V hosts. It uses
# only PowerShell remoting (Invoke-Command over WinRM), the standard
# management channel that Windows Admin Center and SCVMM use; nothing is
# copied to, installed as a service on or scheduled on the nodes.
#   Read  reads each node (Windows version, domain, roles, adapters, switches,
#         disks, iSCSI and Fibre Channel names, cluster membership) and this
#         computer. It changes nothing.
#   ReadExisting reads the existing Hyper-V host or failover cluster named
#         first in -Computers (a cluster through one of its nodes): its
#         switches, host adapters, storage connections, live migration
#         settings and, for a cluster, its nodes, addresses, quorum, networks
#         and Cluster Shared Volumes, so the plan can match it. It changes
#         nothing.
#   Run   runs one step script written by the application (the file at
#         -StepPath, generated by hvBuildScript) on each node in -Computers,
#         one after another, or on this computer when -Computers is empty.
#         Without -Apply the script only lists what it would change. With
#         -Apply each script gets the SHA-256 of the list the operator
#         approved (from -ApprovedPath) and changes nothing unless the list it
#         computes again is the same; the first failure stops the run.
#         -RestartAfter restarts each node whose approved restart step ran,
#         with Restart-Computer, and waits for it to answer again.
# With -CredentialFromInput an account and any secret arrive as one JSON line
# on standard input, never on a command line, and are used only for this run.
# The result is written to -ResultPath as {"ok":..,"error":..,"result":..}.
# Compatible with Windows PowerShell 3.0 and later.

$ErrorActionPreference = 'Stop'
try { [Console]::OutputEncoding = New-Object System.Text.UTF8Encoding($false) } catch { }

function Write-Line { param([string]$Text) [Console]::Out.WriteLine($Text); [Console]::Out.Flush() }
function Write-Log { param([string]$Message) Write-Line ('{0} {1}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $Message) }
function Write-Result {
    param([bool]$Ok, [string]$ErrorText, $Result)
    $json = ConvertTo-Json -InputObject @{ ok = $Ok; error = $ErrorText; result = $Result } -Depth 9 -Compress
    [IO.File]::WriteAllText($ResultPath, $json, (New-Object System.Text.UTF8Encoding($false)))
}
function Test-Local {
    param([string]$Name)
    if (-not $Name -or $Name -eq '.' -or $Name -eq 'localhost') { return $true }
    $short = $Name.Split('.')[0]
    return $short -eq $env:COMPUTERNAME
}
function ConvertFrom-StepOutput {
    param($Output)
    $last = [string](@($Output | ForEach-Object { [string]$_ } | Where-Object { $_.Trim().StartsWith('{') }) | Select-Object -Last 1)
    if (-not $last) { throw 'The step wrote no result.' }
    return ConvertFrom-Json -InputObject $last
}

$readNode = {
    $ErrorActionPreference = 'Stop'
    $ProgressPreference = 'SilentlyContinue'
    $warnings = New-Object System.Collections.ArrayList
    $os = Get-WmiObject -Class Win32_OperatingSystem
    $system = Get-WmiObject -Class Win32_ComputerSystem
    $result = @{
        computer = [string]$env:COMPUTERNAME; caption = [string]$os.Caption; version = [string]$os.Version; build = [int]$os.BuildNumber
        productType = [int]$os.ProductType; domain = [string]$system.Domain; partOfDomain = [bool]$system.PartOfDomain
        hypervisorPresent = [bool]$system.HypervisorPresent; virtualization = $false; pendingRestart = $false
        cores = 0; memoryBytes = [uint64]$system.TotalPhysicalMemory
        features = @{}; adapters = @(); switches = @(); hostNics = @(); disks = @(); initiator = ''; wwpns = @(); portals = @(); cluster = ''; warnings = @()
    }
    try {
        $cpus = @(Get-WmiObject -Class Win32_Processor)
        $result.cores = [int](($cpus | Measure-Object -Property NumberOfCores -Sum).Sum)
        $result.virtualization = [bool]($cpus | Where-Object { $_.VirtualizationFirmwareEnabled })
    } catch { [void]$warnings.Add('Processor: ' + $_.Exception.Message) }
    foreach ($key in @('HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Component Based Servicing\RebootPending', 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\WindowsUpdate\Auto Update\RebootRequired')) {
        if (Test-Path -LiteralPath $key) { $result.pendingRestart = $true }
    }
    if (Get-Command Get-WindowsFeature -ErrorAction SilentlyContinue) {
        try {
            foreach ($feature in @(Get-WindowsFeature -Name Hyper-V, Hyper-V-PowerShell, Failover-Clustering, RSAT-Clustering-PowerShell, Multipath-IO)) {
                $result.features[[string]$feature.Name] = [string]$feature.InstallState
                if ([string]$feature.InstallState -eq 'InstallPending') { $result.pendingRestart = $true }
            }
        } catch { [void]$warnings.Add('Roles: ' + $_.Exception.Message) }
    }
    try {
        $adapters = New-Object System.Collections.ArrayList
        foreach ($adapter in @(Get-NetAdapter -Physical -ErrorAction Stop)) {
            $switchBound = $false
            try { $binding = Get-NetAdapterBinding -Name $adapter.Name -ComponentID vms_pp -ErrorAction Stop; $switchBound = [bool]$binding.Enabled } catch { }
            $ips = @(Get-NetIPAddress -InterfaceIndex $adapter.ifIndex -AddressFamily IPv4 -ErrorAction SilentlyContinue | Where-Object { $_.PrefixOrigin -ne 'WellKnown' } | ForEach-Object { $_.IPAddress + '/' + $_.PrefixLength })
            $gateway = [bool](Get-NetRoute -InterfaceIndex $adapter.ifIndex -DestinationPrefix '0.0.0.0/0' -ErrorAction SilentlyContinue)
            $vlan = 0
            try { $vlan = [int]$adapter.VlanID } catch { }
            [void]$adapters.Add(@{ name = [string]$adapter.Name; description = [string]$adapter.InterfaceDescription; status = [string]$adapter.Status; mac = [string]$adapter.MacAddress; speedBits = [uint64]$adapter.Speed; ips = $ips; switchBound = $switchBound; gateway = $gateway; vlanId = $vlan })
        }
        $result.adapters = @($adapters)
    } catch { [void]$warnings.Add('Network adapters: ' + $_.Exception.Message) }
    if (Get-Command -Module Hyper-V -Name Get-VMSwitch -ErrorAction SilentlyContinue) {
        try {
            $result.switches = @(Hyper-V\Get-VMSwitch | ForEach-Object { @{ name = [string]$_.Name; type = [string]$_.SwitchType; adapters = @(@($_.NetAdapterInterfaceDescriptions) + @($_.NetAdapterInterfaceDescription) | Where-Object { $_ } | ForEach-Object { [string]$_ }); embedded = [bool]$_.EmbeddedTeamingEnabled } })
            $result.hostNics = @(Hyper-V\Get-VMNetworkAdapter -ManagementOS | ForEach-Object {
                $alias = 'vEthernet (' + [string]$_.Name + ')'
                $ips = @(Get-NetIPAddress -InterfaceAlias $alias -AddressFamily IPv4 -ErrorAction SilentlyContinue | Where-Object { $_.PrefixOrigin -ne 'WellKnown' } | ForEach-Object { $_.IPAddress + '/' + $_.PrefixLength })
                $gateway = [bool](Get-NetRoute -InterfaceAlias $alias -DestinationPrefix '0.0.0.0/0' -ErrorAction SilentlyContinue)
                @{ name = [string]$_.Name; switch = [string]$_.SwitchName; ips = $ips; gateway = $gateway }
            })
        } catch { [void]$warnings.Add('Virtual switches: ' + $_.Exception.Message) }
    }
    try {
        $result.disks = @(Get-Disk | ForEach-Object { @{ number = [int]$_.Number; name = [string]$_.FriendlyName; serial = [string]$_.SerialNumber; uniqueId = [string]$_.UniqueId; sizeBytes = [uint64]$_.Size; style = [string]$_.PartitionStyle; boot = [bool]$_.IsBoot; system = [bool]$_.IsSystem; clustered = [bool]$_.IsClustered; offline = [bool]$_.IsOffline; bus = [string]$_.BusType; partitions = [int]$_.NumberOfPartitions } })
    } catch { [void]$warnings.Add('Disks: ' + $_.Exception.Message) }
    try {
        foreach ($port in @(Get-InitiatorPort -ErrorAction Stop)) {
            if ([string]$port.ConnectionType -eq 'iSCSI') { $result.initiator = [string]$port.NodeAddress }
            if ([string]$port.ConnectionType -eq 'Fibre Channel') { $result.wwpns += [string]$port.PortAddress }
        }
    } catch { }
    try { $result.portals = @(Get-IscsiTargetPortal -ErrorAction Stop | ForEach-Object { [string]$_.TargetPortalAddress + ':' + [string]$_.TargetPortalPortNumber }) } catch { }
    $clusterKey = Get-ItemProperty -LiteralPath 'HKLM:\Cluster' -Name ClusterName -ErrorAction SilentlyContinue
    if ($clusterKey) { $result.cluster = [string]$clusterKey.ClusterName }
    $result.warnings = @($warnings)
    ConvertTo-Json -InputObject $result -Depth 6 -Compress
}

$readTemplate = {
    $ErrorActionPreference = 'Stop'
    $ProgressPreference = 'SilentlyContinue'
    $warnings = New-Object System.Collections.ArrayList
    $os = Get-WmiObject -Class Win32_OperatingSystem
    $system = Get-WmiObject -Class Win32_ComputerSystem
    $result = @{
        computer = [string]$env:COMPUTERNAME; dnsName = ''; caption = [string]$os.Caption; build = [int]$os.BuildNumber
        domain = [string]$system.Domain; partOfDomain = [bool]$system.PartOfDomain; hyperV = $false
        switches = @(); hostNics = @(); host = $null; cluster = ''; warnings = @()
        storage = @{ initiator = ''; portals = @(); targets = @(); mpio = $false; fc = $false; arrays = @(); adapters = @() }
    }
    if ($system.PartOfDomain) { $result.dnsName = [string]$env:COMPUTERNAME + '.' + [string]$system.Domain }
    $clusterKey = Get-ItemProperty -LiteralPath 'HKLM:\Cluster' -Name ClusterName -ErrorAction SilentlyContinue
    if ($clusterKey) { $result.cluster = [string]$clusterKey.ClusterName }
    $physical = @(Get-NetAdapter -Physical -ErrorAction SilentlyContinue)
    $byDescription = @{}
    foreach ($adapter in $physical) { $byDescription[[string]$adapter.InterfaceDescription] = $adapter }
    $jumboOf = { param($name) $p = Get-NetAdapterAdvancedProperty -Name $name -RegistryKeyword '*JumboPacket' -ErrorAction SilentlyContinue; if ($p) { return [int]([string]$p.RegistryValue) } ; return 0 }
    if (Get-Command -Module Hyper-V -Name Get-VMSwitch -ErrorAction SilentlyContinue) {
        $result.hyperV = $true
        try {
            $switches = New-Object System.Collections.ArrayList
            foreach ($sw in @(Hyper-V\Get-VMSwitch)) {
                $descriptions = @(@($sw.NetAdapterInterfaceDescriptions) + @($sw.NetAdapterInterfaceDescription) | Where-Object { $_ } | ForEach-Object { [string]$_ } | Select-Object -Unique)
                $names = New-Object System.Collections.ArrayList
                $speeds = New-Object System.Collections.ArrayList
                $jumbo = $false
                $team = $false
                foreach ($description in $descriptions) {
                    $members = @()
                    if ($byDescription.ContainsKey($description)) { $members = @($byDescription[$description]) }
                    elseif (Get-Command Get-NetLbfoTeam -ErrorAction SilentlyContinue) {
                        foreach ($lbfo in @(Get-NetLbfoTeam -ErrorAction SilentlyContinue)) {
                            $nic = Get-NetAdapter -Name $lbfo.Name -ErrorAction SilentlyContinue
                            if ($nic -and [string]$nic.InterfaceDescription -eq $description) { $team = $true; $members = @($physical | Where-Object { @($lbfo.Members) -contains $_.Name }) }
                        }
                    }
                    foreach ($member in $members) {
                        [void]$names.Add([string]$member.Name)
                        [void]$speeds.Add([int]([uint64]$member.Speed / 1000000))
                        if ((& $jumboOf $member.Name) -ge 9000) { $jumbo = $true }
                    }
                }
                $lb = ''
                if ($sw.EmbeddedTeamingEnabled) { try { $lb = [string](Hyper-V\Get-VMSwitchTeam -Name $sw.Name).LoadBalancingAlgorithm } catch { } }
                [void]$switches.Add(@{ name = [string]$sw.Name; type = [string]$sw.SwitchType; embedded = [bool]$sw.EmbeddedTeamingEnabled; team = $team; adapters = @($names); speedsMb = @($speeds); loadBalancing = $lb; managementOs = [bool]$sw.AllowManagementOS; jumbo = $jumbo })
            }
            $result.switches = @($switches)
            $result.hostNics = @(Hyper-V\Get-VMNetworkAdapter -ManagementOS | ForEach-Object {
                $alias = 'vEthernet (' + [string]$_.Name + ')'
                $vlan = ''
                try { $v = Hyper-V\Get-VMNetworkAdapterVlan -ManagementOS -VMNetworkAdapterName $_.Name | Select-Object -First 1; if ([string]$v.OperationMode -eq 'Access') { $vlan = [string]$v.AccessVlanId } } catch { }
                $ips = @(Get-NetIPAddress -InterfaceAlias $alias -AddressFamily IPv4 -ErrorAction SilentlyContinue | Where-Object { $_.PrefixOrigin -ne 'WellKnown' } | ForEach-Object { $_.IPAddress + '/' + $_.PrefixLength })
                $gateway = [bool](Get-NetRoute -InterfaceAlias $alias -DestinationPrefix '0.0.0.0/0' -ErrorAction SilentlyContinue)
                @{ name = [string]$_.Name; switch = [string]$_.SwitchName; vlan = $vlan; ips = $ips; gateway = $gateway }
            })
        } catch { [void]$warnings.Add('Virtual switches: ' + $_.Exception.Message) }
        try {
            $vmHost = Hyper-V\Get-VMHost
            $performance = ''
            if ($vmHost.PSObject.Properties['VirtualMachineMigrationPerformanceOption']) { $performance = [string]$vmHost.VirtualMachineMigrationPerformanceOption }
            $result.host = @{
                migrationEnabled = [bool]$vmHost.VirtualMachineMigrationEnabled; auth = [string]$vmHost.VirtualMachineMigrationAuthenticationType
                max = [int]$vmHost.MaximumVirtualMachineMigrations; maxStorage = [int]$vmHost.MaximumStorageMigrations; performance = $performance
                vmPath = [string]$vmHost.VirtualMachinePath; vhdPath = [string]$vmHost.VirtualHardDiskPath; useAnyNetwork = [bool]$vmHost.UseAnyNetworkForMigration
                migrationNetworks = @(Hyper-V\Get-VMMigrationNetwork -ErrorAction SilentlyContinue | ForEach-Object { [string]$_.Subnet })
            }
        } catch { [void]$warnings.Add('Live migration settings: ' + $_.Exception.Message) }
    }
    try {
        foreach ($port in @(Get-InitiatorPort -ErrorAction Stop)) {
            if ([string]$port.ConnectionType -eq 'iSCSI') { $result.storage.initiator = [string]$port.NodeAddress }
            if ([string]$port.ConnectionType -eq 'Fibre Channel') { $result.storage.fc = $true }
        }
    } catch { }
    try { $result.storage.portals = @(Get-IscsiTargetPortal -ErrorAction Stop | ForEach-Object { [string]$_.TargetPortalAddress + ':' + [string]$_.TargetPortalPortNumber }) } catch { }
    try { $result.storage.targets = @(Get-IscsiTarget -ErrorAction Stop | Where-Object { $_.IsConnected } | ForEach-Object { [string]$_.NodeAddress }) } catch { }
    try {
        $used = New-Object System.Collections.ArrayList
        foreach ($connection in @(Get-IscsiConnection -ErrorAction Stop)) {
            $address = Get-NetIPAddress -IPAddress ([string]$connection.InitiatorAddress) -AddressFamily IPv4 -ErrorAction SilentlyContinue | Select-Object -First 1
            if (-not $address) { continue }
            $nic = $physical | Where-Object { $_.ifIndex -eq $address.InterfaceIndex } | Select-Object -First 1
            if ($nic -and -not ($used | Where-Object { $_.adapter -eq [string]$nic.Name })) { [void]$used.Add(@{ adapter = [string]$nic.Name; ip = [string]$address.IPAddress + '/' + [string]$address.PrefixLength }) }
        }
        $result.storage.adapters = @($used)
    } catch { }
    if (Get-Command Get-WindowsFeature -ErrorAction SilentlyContinue) {
        try { $result.storage.mpio = ([string](Get-WindowsFeature -Name Multipath-IO).InstallState -eq 'Installed') } catch { }
    }
    if ($result.storage.mpio -and (Get-Command Get-MSDSMSupportedHW -ErrorAction SilentlyContinue)) {
        try { $result.storage.arrays = @(Get-MSDSMSupportedHW -ErrorAction Stop | Where-Object { [string]$_.VendorId -ne 'Vendor 8' -and [string]$_.VendorId -ne 'MSFT2005' -and [string]$_.VendorId -ne 'MSFT2011' } | ForEach-Object { @{ vendor = ([string]$_.VendorId).Trim(); product = ([string]$_.ProductId).Trim() } }) } catch { }
    }
    $result.warnings = @($warnings)
    ConvertTo-Json -InputObject $result -Depth 6 -Compress
}

$readCluster = {
    param([string]$Name)
    $ErrorActionPreference = 'Stop'
    Import-Module FailoverClusters
    $cluster = Get-Cluster -Name $Name
    $result = @{ name = [string]$cluster.Name; domain = [string]$cluster.Domain; nodes = @(); addresses = @(); witnessType = ''; witness = ''; witnessPath = ''; networks = @(); migrationExclude = @(); csvs = @(); vms = 0 }
    $result.nodes = @(Get-ClusterNode -Cluster $Name | ForEach-Object { @{ name = [string]$_.Name; state = [string]$_.State } })
    $resources = @(Get-ClusterResource -Cluster $Name)
    $result.addresses = @($resources | Where-Object { [string]$_.ResourceType -eq 'IP Address' -and [string]$_.OwnerGroup -eq 'Cluster Group' } | ForEach-Object { [string]($_ | Get-ClusterParameter -Name Address).Value })
    $result.vms = @($resources | Where-Object { [string]$_.ResourceType -eq 'Virtual Machine' }).Count
    try {
        $quorum = Get-ClusterQuorum -Cluster $Name
        if ($quorum.QuorumResource) {
            $witness = $quorum.QuorumResource
            $result.witnessType = [string]$witness.ResourceType
            $result.witness = [string]$witness.Name
            if ($result.witnessType -eq 'File Share Witness') { $result.witnessPath = [string]($witness | Get-ClusterParameter -Name SharePath).Value }
            if ($result.witnessType -eq 'Cloud Witness') { $result.witnessPath = [string]($witness | Get-ClusterParameter -Name AccountName).Value }
        }
    } catch { }
    $type = Get-ClusterResourceType -Cluster $Name -Name 'Virtual Machine' -ErrorAction SilentlyContinue
    if ($type) { $result.migrationExclude = @(([string]($type | Get-ClusterParameter -Name MigrationExcludeNetworks).Value).Split(';') | Where-Object { $_ }) }
    $result.networks = @(Get-ClusterNetwork -Cluster $Name | ForEach-Object { @{ id = [string]$_.Id; name = [string]$_.Name; address = [string]$_.Address; mask = [string]$_.AddressMask; role = [int]$_.Role; migration = (@($result.migrationExclude) -notcontains [string]$_.Id) } })
    $result.csvs = @(Get-ClusterSharedVolume -Cluster $Name -ErrorAction SilentlyContinue | ForEach-Object {
        $info = @($_.SharedVolumeInfo)[0]
        $size = [uint64]0; $free = [uint64]0; $path = ''
        if ($info) { $path = [string]$info.FriendlyVolumeName; try { $size = [uint64]$info.Partition.Size; $free = [uint64]$info.Partition.FreeSpace } catch { } }
        @{ name = [string]$_.Name; path = $path; sizeBytes = $size; freeBytes = $free }
    })
    ConvertTo-Json -InputObject $result -Depth 5 -Compress
}

try {
    $invoke = @{ ErrorAction = 'Stop' }
    $secrets = $null
    $credential = $null
    if ($CredentialFromInput) {
        $line = [Console]::In.ReadLine()
        if (-not $line) { throw 'No account was given on standard input.' }
        $account = ConvertFrom-Json -InputObject $line
        $line = $null
        if ($account.user) {
            $secure = New-Object System.Security.SecureString
            foreach ($character in ([string]$account.password).ToCharArray()) { $secure.AppendChar($character) }
            $secure.MakeReadOnly()
            $credential = New-Object System.Management.Automation.PSCredential([string]$account.user, $secure)
            $invoke.Credential = $credential
        }
        if ($account.secrets) { $secrets = @{ cloudKey = [string]$account.secrets.cloudKey } }
        $account = $null
    }
    $targets = @($Computers.Split(',') | ForEach-Object { $_.Trim() } | Where-Object { $_ })
    if ($Mode -eq 'ReadExisting') {
        if ($targets.Count -eq 0) { throw 'Type the cluster or host to read.' }
        $name = $targets[0]
        $from = $name
        $localModule = [bool](Get-Module -ListAvailable -Name FailoverClusters)
        $clusterFacts = $null
        $clusterName = ''
        # A cluster name: read the cluster from here and pick a node that is
        # up to read its setup.
        if ($localModule) {
            try {
                Import-Module FailoverClusters
                $found = Get-Cluster -Name $name -ErrorAction Stop
                $clusterName = [string]$found.Name
                $up = @(Get-ClusterNode -Cluster $name | Where-Object { [string]$_.State -eq 'Up' } | ForEach-Object { [string]$_.Name })
                if ($up.Count -eq 0) { throw ('No node of cluster ' + $clusterName + ' is up.') }
                if (-not (@($up | ForEach-Object { $_.Split('.')[0].ToLower() }) -contains $name.Split('.')[0].ToLower())) { $from = $up[0] }
            } catch {
                if ($clusterName) { throw }
            }
        }
        Write-Log ('Reading ' + $from + '.')
        if (Test-Local $from) { $text = & $readTemplate } else { $text = Invoke-Command @invoke -ComputerName $from -ScriptBlock $readTemplate }
        $template = ConvertFrom-Json -InputObject ([string]($text | Select-Object -Last 1))
        if (-not $clusterName -and $template.cluster) { $clusterName = [string]$template.cluster }
        $clusterError = ''
        if ($clusterName) {
            Write-Log ('Reading cluster ' + $clusterName + '.')
            try {
                if ($localModule) { $text = & $readCluster $clusterName }
                elseif (Test-Local $from) { throw 'The Failover Cluster Module for Windows PowerShell is not installed here.' }
                else { $text = Invoke-Command @invoke -ComputerName $from -ScriptBlock $readCluster -ArgumentList $clusterName }
                $clusterFacts = ConvertFrom-Json -InputObject ([string]($text | Select-Object -Last 1))
            } catch {
                $clusterError = $_.Exception.Message
                Write-Log ('Reading cluster ' + $clusterName + ' failed: ' + $clusterError)
            }
        }
        Write-Result $true '' @{ readFrom = $from; template = $template; cluster = $clusterFacts; clusterError = $clusterError }
        exit 0
    }
    if ($Mode -eq 'Read') {
        $nodes = @{}
        foreach ($computer in $targets) {
            Write-Log ('Reading ' + $computer + '.')
            try {
                if (Test-Local $computer) { $text = & $readNode } else { $text = Invoke-Command @invoke -ComputerName $computer -ScriptBlock $readNode }
                $nodes[$computer] = @{ ok = $true; error = ''; facts = (ConvertFrom-Json -InputObject ([string]($text | Select-Object -Last 1))) }
            } catch {
                $nodes[$computer] = @{ ok = $false; error = $_.Exception.Message; facts = $null }
                Write-Log ('Reading ' + $computer + ' failed: ' + $_.Exception.Message)
            }
        }
        $system = Get-WmiObject -Class Win32_ComputerSystem
        $os = Get-WmiObject -Class Win32_OperatingSystem
        $local = @{
            computer = [string]$env:COMPUTERNAME; domain = [string]$system.Domain; partOfDomain = [bool]$system.PartOfDomain
            server = ([int]$os.ProductType -ne 1); caption = [string]$os.Caption
            account = [Security.Principal.WindowsIdentity]::GetCurrent().Name
            admin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
            clusterModule = [bool](Get-Module -ListAvailable -Name FailoverClusters)
        }
        Write-Result $true '' @{ nodes = $nodes; local = $local }
        exit 0
    }

    if (-not $StepPath -or -not (Test-Path -LiteralPath $StepPath -PathType Leaf)) { throw 'The step script is missing.' }
    $body = [IO.File]::ReadAllText($StepPath)
    $approved = @{}
    if ($ApprovedPath) {
        $parsed = ConvertFrom-Json -InputObject ([IO.File]::ReadAllText($ApprovedPath))
        foreach ($property in $parsed.PSObject.Properties) { $approved[$property.Name] = [string]$property.Value }
    }
    if ($targets.Count -eq 0) { $targets = @('.') }
    $runs = New-Object System.Collections.ArrayList
    $stopped = $false
    foreach ($computer in $targets) {
        $run = @{ computer = $computer; ok = $false; error = ''; output = $null; restarted = $false; skipped = $false }
        if ($stopped) { $run.skipped = $true; [void]$runs.Add($run); continue }
        $hash = ''
        if ($approved.ContainsKey($computer)) { $hash = $approved[$computer] }
        if ($Apply -and -not $hash) { $run.error = 'This computer has no approved preview.'; [void]$runs.Add($run); $stopped = $true; continue }
        $where = $computer
        if ($computer -eq '.') { $where = 'this computer' }
        if ($Apply) { Write-Log ('Applying on ' + $where + '.') } else { Write-Log ('Previewing on ' + $where + '.') }
        try {
            $block = [scriptblock]::Create($body)
            if (Test-Local $computer) {
                $output = & $block ([bool]$Apply) $hash $secrets
            } else {
                $output = Invoke-Command @invoke -ComputerName $computer -ScriptBlock $block -ArgumentList ([bool]$Apply), $hash, $null
            }
            $run.output = ConvertFrom-StepOutput $output
            $run.ok = $true
            if ($Apply -and ($run.output.error -or $run.output.refused)) { $stopped = $true }
            if ($Apply -and $RestartAfter -and -not $run.output.error -and -not $run.output.refused -and @($run.output.applied).Count -gt 0) {
                if (Test-Local $computer) {
                    $run.error = 'This computer is not restarted by the application. Restart it yourself.'
                    $stopped = $true
                } else {
                    Write-Log ('Restarting ' + $computer + ' and waiting for it to answer again.')
                    $restart = @{ ComputerName = $computer; Force = $true; Wait = $true; For = 'WinRM'; Timeout = 1800; Delay = 10; ErrorAction = 'Stop' }
                    if ($credential) { $restart.Credential = $credential }
                    try { Restart-Computer @restart; $run.restarted = $true; Write-Log ($computer + ' is back.') }
                    catch { $run.error = 'The restart of ' + $computer + ' did not finish: ' + $_.Exception.Message; $stopped = $true }
                }
            }
        } catch {
            $run.error = $_.Exception.Message
            Write-Log ($where + ': ' + $_.Exception.Message)
            if ($Apply) { $stopped = $true }
        }
        [void]$runs.Add($run)
    }
    Write-Result $true '' @{ runs = @($runs) }
} catch {
    Write-Result $false $_.Exception.Message $null
    exit 1
}
