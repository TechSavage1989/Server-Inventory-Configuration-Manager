// csvSafe stops spreadsheet programs treating names from vCenter as formulas.
func csvSafe(value string) string {
	if value != "" && strings.ContainsAny(value[:1], "=+-@\t\r") {
		return "'" + value
	}
	return value
}

func writeCSVFile(path string, header []string, rows [][]string) error {
	var buffer bytes.Buffer
	buffer.WriteString("\xef\xbb\xbf") // Excel reads UTF-8 with a byte order mark.
	writer := csv.NewWriter(&buffer)
	_ = writer.Write(header)
	for _, row := range rows {
		safe := make([]string, len(row))
		for index, value := range row {
			safe[index] = csvSafe(value)
		}
		_ = writer.Write(safe)
	}
	writer.Flush()
	if err := writer.Error(); err != nil {
		return err
	}
	return os.WriteFile(path, buffer.Bytes(), 0600)
}

func gib(value int64) string {
	return strconv.FormatFloat(float64(value)/(1<<30), 'f', 1, 64)
}

func findingSummary(readiness *vmReadiness, severity string) string {
	if readiness == nil {
		return ""
	}
	messages := []string{}
	for _, finding := range readiness.Findings {
		if finding.Severity == severity {
			messages = append(messages, finding.Message)
		}
	}
	return strings.Join(messages, " | ")
}

