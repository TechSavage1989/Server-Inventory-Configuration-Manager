// writeVMwarePlanOutputs writes the runbook (HTML and Word) and the plan CSV
// into folder.
func writeVMwarePlanOutputs(folder string, inventory *vmInventory, plan vmPlan) (string, string, error) {
	if err := os.MkdirAll(folder, 0700); err != nil {
		return "", "", err
	}
	waves := buildRunbook(plan, inventory)
	sizing := sizePlan(plan, inventory)
	rolling := analyzeRolling(plan, inventory)
	stages, rollingNotes, rollingStorage, scenario := vmRollingRunbookStages(rolling), []string{}, []vmStorageReuse{}, ""
	if rolling != nil {
		rollingNotes, rollingStorage = rolling.Notes, rolling.Storage
		info, _ := vmScenarioFor(vmScenarioRolling)
		scenario = info.Name
	}
	var page bytes.Buffer
	if err := vmRunbookTmpl.Execute(&page, map[string]any{"Inventory": inventory, "Plan": plan, "Roles": vmMoveRoles(plan.Target), "Waves": waves, "Sizing": sizing, "Rolling": stages, "RollingNotes": rollingNotes, "RollingStorage": rollingStorage, "Scenario": scenario, "Style": template.CSS(vmReportStylesheet + vmRunbookStyle), "Script": template.JS(vmRunbookScript), "ScriptHash": vmRunbookScriptHash(), "Generator": vmReportGeneratorLine}); err != nil {
		return "", "", err
	}
	runbook := filepath.Join(folder, vmRunbookReport)
	if err := os.WriteFile(runbook, page.Bytes(), 0600); err != nil {
		return "", "", err
	}
	if err := writeRunbookDocx(filepath.Join(folder, vmRunbookDocx), inventory, plan, waves, sizing, rolling); err != nil {
		return "", "", err
	}
	rows := [][]string{}
	for _, wave := range waves {
		for _, item := range wave.VMs {
			vm := item.VM
			networks, storage := []string{}, []string{}
			for _, nic := range vm.NICs {
				mapped := plan.networkFor(nic.Network)
				value := nic.Network + " > " + mapped.TargetName
				if mapped.TargetVLAN != "" {
					value += " (VLAN " + mapped.TargetVLAN + ")"
				}
				networks = append(networks, value)
			}
			for _, disk := range vm.Disks {
				storage = append(storage, disk.Datastore+" > "+plan.storageFor(disk.Datastore))
			}
			generation := ""
			if item.Readiness.Generation > 0 {
				generation = strconv.Itoa(item.Readiness.Generation)
			}
			rows = append(rows, []string{wave.Label, vm.Name, vmTargetLabel(plan.Target), item.Readiness.Status, generation, strconv.Itoa(vm.CPUs), strconv.FormatInt(vm.MemoryMB, 10), gib(vm.ProvisionedBytes), gib(vm.UsedBytes), strings.Join(networks, "; "), strings.Join(storage, "; "), findingSummary(&item.Readiness, vmSeverityBlocker), findingSummary(&item.Readiness, vmSeverityWarning), item.Entry.Notes})
		}
	}
	csvPath := filepath.Join(folder, vmPlanCSV)
	err := writeCSVFile(csvPath, []string{"Wave", "VM", "Target", "Readiness", "Generation", "vCPUs", "MemoryMB", "ProvisionedGB", "UsedGB", "Networks", "Storage", "Blockers", "Warnings", "Notes"}, rows)
	return runbook, csvPath, err
}

// vmRunbookScriptHash is the CSP source that allows exactly vmRunbookScript.
func vmRunbookScriptHash() string {
	sum := sha256.Sum256([]byte(vmRunbookScript))
	return "sha256-" + base64.StdEncoding.EncodeToString(sum[:])
}
